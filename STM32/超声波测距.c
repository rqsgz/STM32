static void oled_char(int x,int y,char c){
  if(c<32||c>126)c=' '; const uint8_t *f=font5x7[c-32];
  for(int col=0;col<5;col++){ uint8_t l=f[col]; for(int row=0;row<7;row++) oled_pixel(x+col,y+row,(l>>row)&1); }
}
static void oled_str(int x,int y,const char *s){ while(*s){ oled_char(x,y,*s++); x+=6; } }

int main(void){
  dwt_init(); oled_init();

  RCC->AHB1ENR|=RCC_AHB1ENR_GPIOCEN; GPIOC->MODER|=(1<<(12*2)); buzzer_off();
  RCC->AHB1ENR|=RCC_AHB1ENR_GPIOBEN; GPIOB->MODER|=(1<<(0*2));
  GPIOB->PUPDR&=~(3<<(2*2)); /* PB2 无上下拉 */
  RCC->APB2ENR|=RCC_APB2ENR_SYSCFGEN; SYSCFG->EXTICR[0]|=(1<<8);
  EXTI->IMR|=EXTI_IMR_MR2; EXTI->RTSR|=EXTI_RTSR_TR2; EXTI->FTSR|=EXTI_FTSR_TR2;
  NVIC_SetPriority(EXTI2_IRQn,1); NVIC_EnableIRQ(EXTI2_IRQn);

  oled_str(0,10,"HC-SR04 Ready"); oled_refresh();
  delay_ms(2000); /* 等传感器稳定 */

  char s[20];
  while(1){
    int d=hcsr04_read(); oled_clear(); oled_str(0,0,"Ultrasonic Range");
    if(d<0){ oled_str(0,22,"Out of range"); buzzer_off(); }
    else {
      sprintf(s,"%d cm  raw:%luus",d,echo_raw/16); oled_str(0,14,s);
      int bar=(d>200?200:d)*120/200;
      for(int x=0;x<bar;x++) for(int y=30;y<38;y++) oled_pixel(x+4,y,1);
      if(d<10){ oled_str(8,44,"ALARM! <10cm"); buzzer_on(); }
      else buzzer_off();
    }
    oled_refresh(); delay_ms(200);
  }
}
