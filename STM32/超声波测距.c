/*
 * HC-SR04 超声波测距 + OLED + 蜂鸣器
 * 接线:
 *   HC-SR04: VCC→3.3V GND→GND Trig→PB0 Echo→PB1
 *   蜂鸣器:  VCC→3.3V GND→GND I/O→PC12
 *   OLED:    VCC→3.3V GND→GND SCL→PB5 SDA→PB6
 */

static void buzzer_on(void){ GPIOC->BSRR=(uint32_t)(1U<<12)<<16; }
static void buzzer_off(void){ GPIOC->BSRR=(1U<<12); }

static void dwt_init(void){ CoreDebug->DEMCR|=CoreDebug_DEMCR_TRCENA_Msk; DWT->CYCCNT=0; DWT->CTRL|=DWT_CTRL_CYCCNTENA_Msk; }
static uint32_t dwt_get(void){ return DWT->CYCCNT; }
static void delay_us(uint32_t us){ uint32_t s=DWT->CYCCNT, t=us*16; while((DWT->CYCCNT-s)<t); }
static void delay_ms(uint32_t ms){ while(ms--) delay_us(1000); }

static volatile uint32_t echo_start=0, echo_end=0, echo_raw=0;
static volatile int echo_done=0;

void EXTI2_IRQHandler(void){
  if(EXTI->PR & EXTI_PR_PR2){
    EXTI->PR=EXTI_PR_PR2;
    if(GPIOB->IDR & GPIO_PIN_2){ echo_start=dwt_get(); }
    else { echo_end=dwt_get(); echo_done=1; }
  }
}

static void trig_pulse(void){ GPIOB->BSRR=GPIO_PIN_0; delay_us(15); GPIOB->BSRR=(uint32_t)GPIO_PIN_0<<16; }

static int hcsr04_read(void){
  echo_done=0; echo_start=0; trig_pulse();
  uint32_t t=dwt_get();
  while(!echo_start && (dwt_get()-t)<3200000); /* 200ms */
  if(!echo_start) return -1;
  t=dwt_get();
  while(!echo_done && (dwt_get()-t)<480000);
  if(!echo_done) return -1;
  uint32_t e=echo_end-echo_start;
  echo_raw=e; echo_start=echo_end=echo_done=0;
  return (int)(e/(16*58));
}

#define SCL_PORT GPIOB
#define SCL_PIN  5
#define SDA_PORT GPIOB
#define SDA_PIN  6

static void i2c_init(void){
  RCC->AHB1ENR|=RCC_AHB1ENR_GPIOBEN;
  SCL_PORT->OTYPER|=(1<<SCL_PIN)|(1<<SDA_PIN); SCL_PORT->OSPEEDR|=(3<<(SCL_PIN*2))|(3<<(SDA_PIN*2));
  SCL_PORT->PUPDR&=~((3<<(SCL_PIN*2))|(3<<(SDA_PIN*2))); SCL_PORT->MODER|=(1<<(SCL_PIN*2))|(1<<(SDA_PIN*2));
  SCL_PORT->BSRR=(1U<<SCL_PIN)|(1U<<SDA_PIN);
}
static void SCL_H(void){ SCL_PORT->BSRR=(1U<<SCL_PIN); }
static void SCL_L(void){ SCL_PORT->BSRR=(uint32_t)(1U<<SCL_PIN)<<16; }
static void SDA_H(void){ SDA_PORT->BSRR=(1U<<SDA_PIN); }
static void SDA_L(void){ SDA_PORT->BSRR=(uint32_t)(1U<<SDA_PIN)<<16; }
static void i2c_start(void){ SDA_H(); delay_us(2); SCL_H(); delay_us(2); SDA_L(); delay_us(2); SCL_L(); }
static void i2c_stop(void){ SDA_L(); delay_us(2); SCL_H(); delay_us(2); SDA_H(); delay_us(2); }
static int i2c_write(uint8_t d){
  for(int i=0;i<8;i++,d<<=1){ if(d&0x80)SDA_H();else SDA_L(); delay_us(1); SCL_H(); delay_us(2); SCL_L(); delay_us(1); }
  SDA_H(); delay_us(1); SCL_H(); delay_us(1); int a=(SDA_PORT->IDR&(1U<<SDA_PIN))?1:0; SCL_L(); delay_us(1); return a;
}

#define OLED_ADDR 0x3C
static void oled_cmd(uint8_t c){ i2c_start(); i2c_write(OLED_ADDR<<1); i2c_write(0x00); i2c_write(c); i2c_stop(); }
static void oled_data(uint8_t *b,int n){ i2c_start(); i2c_write(OLED_ADDR<<1); i2c_write(0x40); for(int i=0;i<n;i++) i2c_write(b[i]); i2c_stop(); }
static void oled_init(void){
  i2c_init(); delay_ms(100);
  uint8_t init[]={0xAE,0xD5,0x80,0xA8,0x3F,0xD3,0x00,0x40,0x8D,0x14,0x20,0x00,0xA1,0xC8,0xDA,0x12,0x81,0xCF,0xD9,0xF1,0xDB,0x40,0xA4,0xA6,0xAF};
  for(int i=0;i<(int)sizeof(init);i++) oled_cmd(init[i]);
}
static uint8_t oled_buf[128*8];
static void oled_clear(void){ memset(oled_buf,0,sizeof(oled_buf)); }
static void oled_refresh(void){ for(int p=0;p<8;p++){ oled_cmd(0xB0+p); oled_cmd(0x00); oled_cmd(0x10); oled_data(oled_buf+p*128,128); } }
static void oled_pixel(int x,int y,int c){ if(x<0||x>=128||y<0||y>=64)return; if(c) oled_buf[x+(y/8)*128]|=(1<<(y%8)); else oled_buf[x+(y/8)*128]&=~(1<<(y%8)); }
