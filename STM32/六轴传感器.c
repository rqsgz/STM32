static void oled_char(int x,int y,char c){
  if(c<32||c>126) c=' '; const uint8_t *f=font5x7[c-32];
  for(int col=0;col<5;col++){ uint8_t line=f[col]; for(int row=0;row<7;row++) oled_pixel(x+col,y+row,(line>>row)&1); }
}
static void oled_str(int x,int y,const char *s){ while(*s){ oled_char(x,y,*s++); x+=6; } }

/* I2C 探测 */
static int i2c_probe(uint8_t addr){
  i2c_start(); int r=i2c_write(addr<<1); i2c_stop(); return !r;
}

/* MPU6050 */
static uint8_t mpu_addr;
static void mpu_write(uint8_t reg,uint8_t v){ i2c_start(); i2c_write(mpu_addr<<1); i2c_write(reg); i2c_write(v); i2c_stop(); }
static void mpu_read(uint8_t reg,uint8_t *b,int n){
  i2c_start(); i2c_write(mpu_addr<<1); i2c_write(reg);
  i2c_start(); i2c_write((mpu_addr<<1)|1);
  for(int i=0;i<n-1;i++) b[i]=i2c_read(0); b[n-1]=i2c_read(1); i2c_stop();
}

int main(void){
  oled_init(); oled_clear();
  oled_str(0,0,"I2C Scan...");
  oled_refresh(); delay_ms(500);

  char s[20];
  int ok68=i2c_probe(0x68), ok69=i2c_probe(0x69);

  oled_clear();
  sprintf(s,"MPU(0x68): %s",ok68?"OK":"NO"); oled_str(0,0,s);
  sprintf(s,"MPU(0x69): %s",ok69?"OK":"NO"); oled_str(0,12,s);

  if(!ok68 && !ok69){
    oled_str(0,30,"No MPU6050!");
    oled_str(0,42,"Check VCC/GND/");
    oled_str(0,52,"SCL/SDA/AD0");
    oled_refresh(); while(1)delay_ms(1000);
  }

  mpu_addr=ok68?0x68:0x69;
  sprintf(s,"Use addr 0x%02X",mpu_addr); oled_str(0,24,s);
  oled_refresh(); delay_ms(1500);

  mpu_write(0x6B,0x00); mpu_write(0x1B,0x00); mpu_write(0x1C,0x00);

  oled_clear();
  oled_str(0,0,"MPU6050 Ready!");
  oled_refresh(); delay_ms(1000);

  uint8_t buf[14];
  while(1){
    mpu_read(0x3B,buf,14);
    int16_t ax=(buf[0]<<8)|buf[1], ay=(buf[2]<<8)|buf[3], az=(buf[4]<<8)|buf[5];
    int16_t gx=(buf[8]<<8)|buf[9], gy=(buf[10]<<8)|buf[11], gz=(buf[12]<<8)|buf[13];

    /* 物理单位: ±2g→16384 LSB/g, ±250°/s→131 LSB/(°/s) */
    int ax_mg=(int)(ax*1000L/16384);  /* mg */
    int ay_mg=(int)(ay*1000L/16384);
    int az_mg=(int)(az*1000L/16384);
    int gx_d=(int)(gx*10L/131);       /* 0.1 °/s */
    int gy_d=(int)(gy*10L/131);
    int gz_d=(int)(gz*10L/131);

    oled_clear();
    oled_str(0,0,"MPU6050 6-Axis");
    /* 加速度 */
    sprintf(s,"A: %d.%02dg %d.%02dg",ax_mg/1000,ax_mg%1000/10, ay_mg/1000,ay_mg%1000/10);
    oled_str(0,12,s);
    sprintf(s,"   %d.%02dg",az_mg/1000,az_mg%1000/10);
    oled_str(0,22,s);
    /* 角速度 */
    sprintf(s,"G: %d.%d %d.%d",gx_d/10,gx_d%10, gy_d/10,gy_d%10);
    oled_str(0,34,s);
    sprintf(s,"   %d.%d/s",gz_d/10,gz_d%10);
    oled_str(0,44,s);
    /* 原始值小字 */
    sprintf(s,"raw: %d %d %d",ax,ay,az);
    oled_str(0,56,s);
    oled_refresh();
    delay_ms(150);
  }
}
