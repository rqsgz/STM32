/*
 * SSD1306 OLED (0.96" 128x64) — 软件 I²C
 * 接线: VCC→3.3V  GND→GND  SCL→PB5  SDA→PB6
 *
 * I²C 协议 (软件模拟):
 *   起始: SDA↓ 在 SCL=H 时
 *   停止: SDA↑ 在 SCL=H 时
 *   写字节: 8bit + ACK, MSB first
 *   SSD1306 地址: 0x3C → 写=0x78
 */

/* ---- 引脚 ---- */
#define SCL_PORT GPIOB
#define SCL_PIN  5
#define SDA_PORT GPIOB
#define SDA_PIN  6

static void delay_us(uint32_t us){ while(us--) for(volatile int i=0;i<14;i++) __NOP(); }
static void delay_ms(uint32_t ms){ while(ms--) for(volatile uint32_t i=0;i<8000;i++) __NOP(); }

/* ---- 软件 I²C ---- */
static void i2c_init(void){
  RCC->AHB1ENR|=RCC_AHB1ENR_GPIOBEN;
  /* 开漏输出 */
  SCL_PORT->OTYPER|=(1<<SCL_PIN)|(1<<SDA_PIN);
  SCL_PORT->OSPEEDR|=(3<<(SCL_PIN*2))|(3<<(SDA_PIN*2));
  SCL_PORT->PUPDR&=~((3<<(SCL_PIN*2))|(3<<(SDA_PIN*2))); /* 无内部上拉 */
  SCL_PORT->MODER|=(1<<(SCL_PIN*2))|(1<<(SDA_PIN*2));    /* 输出 */
  SCL_PORT->BSRR=(1U<<SCL_PIN)|(1U<<SDA_PIN); /* 空闲=HIGH */
}

static void SCL_H(void){ SCL_PORT->BSRR=(1U<<SCL_PIN); }
static void SCL_L(void){ SCL_PORT->BSRR=(uint32_t)(1U<<SCL_PIN)<<16; }
static void SDA_H(void){ SDA_PORT->BSRR=(1U<<SDA_PIN); }
static void SDA_L(void){ SDA_PORT->BSRR=(uint32_t)(1U<<SDA_PIN)<<16; }

static void i2c_start(void){ SDA_H(); delay_us(2); SCL_H(); delay_us(2); SDA_L(); delay_us(2); SCL_L(); }
static void i2c_stop(void){ SDA_L(); delay_us(2); SCL_H(); delay_us(2); SDA_H(); delay_us(2); }

static int i2c_write(uint8_t data){
  for(int i=0;i<8;i++,data<<=1){
    if(data&0x80) SDA_H(); else SDA_L();
    delay_us(1); SCL_H(); delay_us(2); SCL_L(); delay_us(1);
  }
  /* ACK: 释放SDA, 从机拉低 */
  SDA_H(); delay_us(1); SCL_H(); delay_us(1);
  int ack=(SDA_PORT->IDR&(1U<<SDA_PIN))?1:0;
  SCL_L(); delay_us(1);
  return ack; /* 0=ACK, 1=NACK */
}

/* ---- SSD1306 命令/数据 ---- */
#define OLED_ADDR 0x3C

static void oled_cmd(uint8_t cmd){
  i2c_start(); i2c_write(OLED_ADDR<<1);   /* 写地址 */
  i2c_write(0x00);                        /* 命令模式 */
  i2c_write(cmd);
  i2c_stop();
}

static void oled_data(uint8_t *buf, int len){
  i2c_start(); i2c_write(OLED_ADDR<<1);
  i2c_write(0x40);                        /* 数据模式 */
  for(int i=0;i<len;i++) i2c_write(buf[i]);
  i2c_stop();
}

/* ---- OLED 初始化 ---- */
static void oled_init(void){
  i2c_init();
  delay_ms(100); /* 等 OLED 上电 */

  uint8_t init[]={
    0xAE,        /* 关显示 */
    0xD5,0x80,   /* 时钟 */
    0xA8,0x3F,   /* 复用比 64 */
    0xD3,0x00,   /* 偏移 */
    0x40,        /* 起始行 */
    0x8D,0x14,   /* 电荷泵 */
    0x20,0x00,   /* 水平寻址 */
    0xA1,        /* 段重映射 */
    0xC8,        /* COM 扫描方向 */
    0xDA,0x12,   /* COM 配置 */
    0x81,0xCF,   /* 对比度 */
    0xD9,0xF1,   /* 预充电 */
    0xDB,0x40,   /* VCOM */
    0xA4,        /* 全屏显示关 */
    0xA6,        /* 正常显示 */
    0xAF         /* 开显示 */
  };
  for(int i=0;i<(int)sizeof(init);i++) oled_cmd(init[i]);
}

/* ---- 绘制 ---- */
static uint8_t oled_buf[128*8]; /* 显存: 128列 × 8页 */

static void oled_clear(void){ memset(oled_buf,0,sizeof(oled_buf)); }

static void oled_refresh(void){
  for(int page=0;page<8;page++){
    oled_cmd(0xB0+page);  /* 设页地址 */
    oled_cmd(0x00);       /* 列低 */
    oled_cmd(0x10);       /* 列高 */
    oled_data(oled_buf+page*128,128);
  }
}

/* 画点 */
static void oled_pixel(int x,int y,int color){
  if(x<0||x>=128||y<0||y>=64) return;
  if(color) oled_buf[x+(y/8)*128]|=(1<<(y%8));
  else      oled_buf[x+(y/8)*128]&=~(1<<(y%8));
}

