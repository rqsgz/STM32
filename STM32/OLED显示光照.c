#define SCL_PORT GPIOB
#define SCL_PIN  5
#define SDA_PORT GPIOB
#define SDA_PIN  6

static void delay_us(uint32_t us){ while(us--) for(volatile int i=0;i<14;i++) __NOP(); }
static void delay_ms(uint32_t ms){ while(ms--) for(volatile uint32_t i=0;i<8000;i++) __NOP(); }

/* ---- 软件 I2C ---- */
static void i2c_init(void){
  RCC->AHB1ENR|=RCC_AHB1ENR_GPIOBEN;
  SCL_PORT->OTYPER|=(1<<SCL_PIN)|(1<<SDA_PIN);
  SCL_PORT->OSPEEDR|=(3<<(SCL_PIN*2))|(3<<(SDA_PIN*2));
  SCL_PORT->PUPDR&=~((3<<(SCL_PIN*2))|(3<<(SDA_PIN*2)));
  SCL_PORT->MODER|=(1<<(SCL_PIN*2))|(1<<(SDA_PIN*2));
  SCL_PORT->BSRR=(1U<<SCL_PIN)|(1U<<SDA_PIN);
}
static void SCL_H(void){ SCL_PORT->BSRR=(1U<<SCL_PIN); }
static void SCL_L(void){ SCL_PORT->BSRR=(uint32_t)(1U<<SCL_PIN)<<16; }
static void SDA_H(void){ SDA_PORT->BSRR=(1U<<SDA_PIN); }
static void SDA_L(void){ SDA_PORT->BSRR=(uint32_t)(1U<<SDA_PIN)<<16; }
static void i2c_start(void){ SDA_H(); delay_us(2); SCL_H(); delay_us(2); SDA_L(); delay_us(2); SCL_L(); }
static void i2c_stop(void){ SDA_L(); delay_us(2); SCL_H(); delay_us(2); SDA_H(); delay_us(2); }
static int i2c_write(uint8_t data){
  for(int i=0;i<8;i++,data<<=1){
    if(data&0x80) SDA_H(); else SDA_L();
    delay_us(1); SCL_H(); delay_us(2); SCL_L(); delay_us(1);
  }
  SDA_H(); delay_us(1); SCL_H(); delay_us(1);
  int ack=(SDA_PORT->IDR&(1U<<SDA_PIN))?1:0;
  SCL_L(); delay_us(1); return ack;
}
static uint8_t i2c_read(int ack){
  uint8_t d=0; SDA_H();
  for(int i=0;i<8;i++){
    d<<=1; SCL_H(); delay_us(1);
    if(SDA_PORT->IDR&(1U<<SDA_PIN)) d|=1;
    SCL_L(); delay_us(1);
  }
  if(ack) SDA_H(); else SDA_L();
  delay_us(1); SCL_H(); delay_us(2); SCL_L(); delay_us(1); SDA_H();
  return d;
}

/* ---- SSD1306 OLED ---- */
#define OLED_ADDR 0x3C
static void oled_cmd(uint8_t cmd){ i2c_start(); i2c_write(OLED_ADDR<<1); i2c_write(0x00); i2c_write(cmd); i2c_stop(); }
static void oled_data(uint8_t *buf, int len){ i2c_start(); i2c_write(OLED_ADDR<<1); i2c_write(0x40); for(int i=0;i<len;i++) i2c_write(buf[i]); i2c_stop(); }
static void oled_init(void){
  i2c_init(); delay_ms(100);
  uint8_t init[]={0xAE,0xD5,0x80,0xA8,0x3F,0xD3,0x00,0x40,0x8D,0x14,0x20,0x00,0xA1,0xC8,0xDA,0x12,0x81,0xCF,0xD9,0xF1,0xDB,0x40,0xA4,0xA6,0xAF};
  for(int i=0;i<(int)sizeof(init);i++) oled_cmd(init[i]);
}
static uint8_t oled_buf[128*8];
static void oled_clear(void){ memset(oled_buf,0,sizeof(oled_buf)); }
static void oled_refresh(void){ for(int page=0;page<8;page++){ oled_cmd(0xB0+page); oled_cmd(0x00); oled_cmd(0x10); oled_data(oled_buf+page*128,128); } }
static void oled_pixel(int x,int y,int color){ if(x<0||x>=128||y<0||y>=64) return; if(color) oled_buf[x+(y/8)*128]|=(1<<(y%8)); else oled_buf[x+(y/8)*128]&=~(1<<(y%8)); }

