static void oled_char(int x,int y,char c){
  if(c<32||c>126) c=' '; const uint8_t *f=font5x7[c-32];
  for(int col=0;col<5;col++){ uint8_t line=f[col]; for(int row=0;row<7;row++) oled_pixel(x+col,y+row,(line>>row)&1); }
}
static void oled_str(int x,int y,const char *s){ while(*s){ oled_char(x,y,*s++); x+=6; } }

/* ---- BH1750 ---- */
#define BH1750_ADDR 0x23
static uint16_t bh1750_read(void){
  i2c_start(); i2c_write(BH1750_ADDR<<1); i2c_write(0x10); i2c_stop(); delay_ms(180);
  i2c_start(); i2c_write((BH1750_ADDR<<1)|1);
  uint16_t raw=i2c_read(0)<<8; raw|=i2c_read(1); i2c_stop();
  return (uint16_t)((uint32_t)raw*10/12);
}

int main(void){
  oled_init(); oled_clear();
  oled_str(10,10,"BH1750 Light");
  oled_str(20,28,"Sensor");
  oled_str(5,48,"SCL=PB5 SDA=PB6");
  oled_refresh(); delay_ms(1500);
  i2c_start(); i2c_write(BH1750_ADDR<<1); i2c_write(0x10); i2c_stop();
  char buf[20]; int prev=0;
  while(1){
    oled_clear();
    uint16_t lx10=bh1750_read();
    uint16_t lux=lx10/10;
    oled_str(0,0,"BH1750 Light Sensor");
    sprintf(buf,"%u.%u lx", lux, lx10%10);
    oled_str(10,16,buf);
    const char *lv;
    if(lux<10)       lv="Very Dark";
    else if(lux<50)  lv="Dark";
    else if(lux<200) lv="Dim";
    else if(lux<500) lv="Indoor";
    else if(lux<1000)lv="Bright";
    else             lv="Very Bright";
    oled_str(10,30,lv);
    int w=(lux>2000?2000:lux)*120/2000;
    for(int x=0;x<w;x++) for(int y=42;y<50;y++) oled_pixel(x+4,y,1);
    if(lx10>prev+3)      oled_str(90,30,"UP");
    else if(lx10<prev-3) oled_str(82,30,"DOWN");
    prev=lx10;
    oled_refresh();
    delay_ms(500);
  }
}
